#[derive(Args)]
pub struct MapArgs {
    #[arg(long = "type", default_value = "FF", value_parser = crate::pitch_lab::parse_type)]
    ty: PitchType,
    /// Write the map as a Markdown file.
    #[arg(long)]
    out: Option<PathBuf>,
}

/// physics-spec §8.3 deliverable: (vertical offset, timing) → (EV, LA, spray, spin) for a
/// perfectly perceived middle-middle pitch from an average pitcher to an average batter.
pub fn map(a: MapArgs) {
    let cage = Cage::average();
    let rel = cage.release(&PitchIntent { ty: a.ty, target_x: 0.0, target_z: 0.75 });
    let mut md = String::new();
    writeln!(md, "# Contact map: {} middle-middle, average RHP vs average RHB\n", a.ty.code()).unwrap();
    writeln!(md, "Generated by `sim-cli cage-map --type {}`. Perfect perception; only the listed placement deviation is applied (agent-models §3.6). Positive vertical offset = bat path above the ball (overcut). Negative timing = early. Spray: negative = pull side for a right-handed batter.\n", a.ty.code()).unwrap();
    writeln!(md, "Each cell: exit velocity (mph) / launch angle (°) / spray (°) / spin (rpm). `—` = miss.\n").unwrap();
    let timings = [-15.0, -10.0, -5.0, 0.0, 5.0, 10.0, 15.0];
    write!(md, "| v-offset \\ timing |").unwrap();
    for t in timings {
        write!(md, " {t:+} ms |").unwrap();
    }
    writeln!(md).unwrap();
    writeln!(md, "|{}", " :--- |".repeat(timings.len() + 1)).unwrap();
    for cm in [-5.0, -4.0, -3.0, -2.5, -2.0, -1.5, -1.0, -0.5, 0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0] {
        write!(md, "| {cm:+.1} cm |").unwrap();
        for t in timings {
            let p = Placement { v_offset: cm / 100.0, t_shift: t / 1000.0, ..Default::default() };
            match cage.swing_with(rel, &p).swing {
                SwingResult::Contact(b) => write!(
                    md,
                    " {:.0} / {:.0} / {:+.0} / {:.0} |",
                    mps_to_mph(b.exit_speed),
                    rad_to_deg(b.launch_angle),
                    rad_to_deg(b.spray_angle),
                    radps_to_rpm(b.contact.ball_after.w.norm())
                )
                .unwrap(),
                _ => write!(md, " — |").unwrap(),
            }
        }
        writeln!(md).unwrap();
    }
    writeln!(md, "\n## Reach (contact station) at perfect timing and height\n").unwrap();
    writeln!(md, "| reach change | contact u (in from knob) | e_n | EV (mph) | LA (°) |\n| :--- | :--- | :--- | :--- | :--- |").unwrap();
    for cm in [-20.0, -15.0, -10.0, -5.0, 0.0, 5.0, 10.0, 15.0, 20.0, 25.0] {
        if let SwingResult::Contact(b) = cage.swing_with(rel, &Placement { reach: cm / 100.0, ..Default::default() }).swing {
            writeln!(md, "| {cm:+} cm | {:.1} | {:.3} | {:.1} | {:.1} |", b.contact.point.u / 0.0254, b.contact.e_n, mps_to_mph(b.exit_speed), rad_to_deg(b.launch_angle)).unwrap();
        } else {
            writeln!(md, "| {cm:+} cm | miss | | | |").unwrap();
        }
    }
    timing_height_grid(&cage, rel, &mut md);
    bat_angle_counterfactual(&cage, rel, &mut md);
    print!("{md}");
    if let Some(p) = a.out {
        std::fs::write(&p, md).unwrap();
        eprintln!("wrote {}", p.display());
    }
}

/// Fable's grid (foul-measures follow-up): the same pitch and aim, timing against the swing's
/// height error, so the joint errors that make fouls can be read off one map.
fn timing_height_grid(cage: &Cage, rel: bb_physics::BallState, md: &mut String) {
    writeln!(md, "\n## Timing × height grid\n").unwrap();
    writeln!(md, "The same pitch and perfectly perceived aim; the swing is shifted in time (negative = early) and moved up or down as a whole (positive = bat over the ball). `·` miss, `F` first lands foul, `g` lands fair but leaves outside the foul lines on the ground (it rolls foul in a game), `o` fair. Fair/foul by first landing, as `pa.rs` calls it.\n").unwrap();
    let ts: Vec<i32> = (-40..=40).step_by(5).collect();
    write!(md, "| cm \\ ms |").unwrap();
    for t in &ts {
        write!(md, " {t:+} |").unwrap();
    }
    writeln!(md, "\n|{}", " :-: |".repeat(ts.len() + 1)).unwrap();
    for cm in (-8..=8).rev() {
        write!(md, "| {cm:+} |").unwrap();
        for t in &ts {
            let p = Placement { v_offset: cm as f64 / 100.0, t_shift: *t as f64 / 1000.0, ..Default::default() };
            let c = match cage.swing_with(rel, &p).swing {
                SwingResult::Contact(b) => {
                    let land = b.flight.last().s.r;
                    if !(land.y > 0.0 && land.x.abs() <= land.y) {
                        "F"
                    } else if b.launch_angle < 0.0 && b.spray_angle.abs() > core::f64::consts::FRAC_PI_4 {
                        "g"
                    } else {
                        "o"
                    }
                }
                _ => "·",
            };
            write!(md, " {c} |").unwrap();
        }
        writeln!(md).unwrap();
    }
}

/// R13 check 4: the same pitch and swing with the bat met at other vertical angles (the
/// pivot swung about the aim point at the same distance, `SwingTemplate::with_bat_angle`).
/// Fair or foul is judged where the ball first comes down, as `pa.rs` does.
fn bat_angle_counterfactual(base: &Cage, rel: bb_physics::BallState, md: &mut String) {
    let (aim, _) = base.aim_perfect(rel).expect("pitch reaches the batter");
    let a0 = rad_to_deg(base.template.bat_angle(&base.batter, aim));
    let angles = [a0, -20.0, -30.0, -35.0];
    let cages: Vec<Cage> = angles
        .iter()
        .map(|deg| {
            let mut c = Cage::average();
            c.template = base.template.with_bat_angle(&base.batter, aim, deg.to_radians());
            c
        })
        .collect();
    let cell = |c: &Cage, p: &Placement| match c.swing_with(rel, p).swing {
        SwingResult::Contact(b) => {
            let land = b.flight.last().s.r;
            let fair = land.y > 0.0 && land.x.abs() <= land.y;
            format!(" {:.0} / {:.0} / {:+.0}{} |", mps_to_mph(b.exit_speed), rad_to_deg(b.launch_angle), rad_to_deg(b.spray_angle), if fair { "" } else { " **F**" })
        }
        _ => " — |".to_string(),
    };
    let header = |md: &mut String, first: &str| {
        write!(md, "| {first} |").unwrap();
        for (i, a) in angles.iter().enumerate() {
            write!(md, " {a:.1}°{} |", if i == 0 { " (now)" } else { "" }).unwrap();
        }
        writeln!(md, "\n|{}", " :--- |".repeat(angles.len() + 1)).unwrap();
    };
    writeln!(md, "\n## Bat-angle counterfactual (R13 check 4)\n").unwrap();
    writeln!(md, "The same pitch and swing with the bat meeting the aim point at other vertical angles (negative = barrel below the hands): the pivot is swung about the aim point at the same distance, so reach and bat speed there are unchanged and the swing plane tilts with the bat. MLB reference: about −25° to −35° (Blast, vendor). Each cell: EV (mph) / LA (°) / spray (°, negative = pull); **F** = first lands foul.\n").unwrap();
    writeln!(md, "### On time, by vertical offset\n").unwrap();
    header(md, "v-offset \\ bat angle");
    for cm in -7..=7 {
        write!(md, "| {cm:+} cm |").unwrap();
        for c in &cages {
            md.push_str(&cell(c, &Placement { v_offset: cm as f64 / 100.0, ..Default::default() }));
        }
        writeln!(md).unwrap();
    }
    writeln!(md, "\n### Square (no vertical offset), by timing\n").unwrap();
    header(md, "timing \\ bat angle");
    for ms in (-40..=40).step_by(5) {
        write!(md, "| {ms:+} ms |").unwrap();
        for c in &cages {
            md.push_str(&cell(c, &Placement { t_shift: ms as f64 / 1000.0, ..Default::default() }));
        }
        writeln!(md).unwrap();
    }
    // Share of a uniform grid of offsets (−7..7 cm, 0.5 cm) × timing (−40..40 ms, 2.5 ms)
    // that makes contact, and of that contact the share that goes foul: a coarse summary.
    writeln!(md, "\n### Grid summary (offsets −7…+7 cm by 0.5, timing −40…+40 ms by 2.5, uniform)\n").unwrap();
    writeln!(md, "| bat angle | contact cells | foul share of contact | pull-side fouls | LA < −10° fouls |\n| :--- | :--- | :--- | :--- | :--- |").unwrap();
    for (a, c) in angles.iter().zip(&cages) {
        let (mut n, mut con, mut foul, mut pull, mut low) = (0u32, 0u32, 0u32, 0u32, 0u32);
        for i in -14..=14 {
            for j in -16..=16 {
                n += 1;
                let p = Placement { v_offset: i as f64 * 0.005, t_shift: j as f64 * 0.0025, ..Default::default() };
                if let SwingResult::Contact(b) = c.swing_with(rel, &p).swing {
                    con += 1;
                    let land = b.flight.last().s.r;
                    if !(land.y > 0.0 && land.x.abs() <= land.y) {
                        foul += 1;
                        pull += (land.x < 0.0) as u32;
                        low += (b.launch_angle < (-10.0f64).to_radians()) as u32;
                    }
                }
            }
        }
        let pc = |a: u32, b: u32| 100.0 * a as f64 / b.max(1) as f64;
        writeln!(md, "| {a:.1}° | {con}/{n} | {:.1}% | {:.1}% | {:.1}% |", pc(foul, con), pc(pull, foul), pc(low, foul)).unwrap();
    }
}

#[derive(Args)]
pub struct CageArgs {
    #[arg(long = "type", default_value = "FF", value_parser = crate::pitch_lab::parse_type)]
    ty: PitchType,
    #[arg(long, default_value_t = 200)]
    n: u32,
    #[arg(long, default_value_t = 1)]
    seed: u64,
    /// Execution-noise scale for both pitcher and batter (1 = average attributes).
    #[arg(long, default_value_t = 1.0)]
    k: f64,
    /// Write a Rerun recording of the first 30 swings.
    #[arg(long)]
    rrd: Option<PathBuf>,
}

/// Noisy pitch and noisy swing, perfect perception: the spread of contact quality that
/// execution noise alone produces (agent-models §3.6 sizing).
pub fn cage(a: CageArgs) {
    let cage = Cage::average();
    #[cfg(feature = "rerun")]
    let rec = a.rrd.as_ref().map(|p| {
        let r = crate::rr::open(p, "sim-cli cage");
        crate::rr::log_field(&r, &bb_physics::zone::Zone::for_batter(cage.batter.height, &Default::default()));
        r
    });
    let (mut contact, mut miss) = (0u32, 0u32);
    let mut evs = Vec::new();
    let mut las = Vec::new();
    let mut buckets = [0u32; 5]; // GB < 10°, LD 10–25°, FB 25–50°, PU > 50°, hard-hit (≥95 mph)
    for i in 0..a.n {
        let rel = cage.release_noisy(&PitchIntent { ty: a.ty, target_x: 0.0, target_z: 0.75 }, a.seed, i, a.k);
        let res = cage.swing_noisy(rel, a.seed, i, a.k);
        match &res.swing {
            SwingResult::Contact(b) => {
                contact += 1;
                let (ev, la) = (mps_to_mph(b.exit_speed), rad_to_deg(b.launch_angle));
                evs.push(ev);
                las.push(la);
                buckets[if la < 10.0 { 0 } else if la < 25.0 { 1 } else if la < 50.0 { 2 } else { 3 }] += 1;
                if ev >= 95.0 {
                    buckets[4] += 1;
                }
            }
            _ => miss += 1,
        }
        #[cfg(feature = "rerun")]
        if let (Some(rec), true) = (&rec, i < 30) {
            crate::rr::log_flight(rec, &format!("world/swings/{i:03}/pitch"), &res.pitch, crate::rr::color_for(a.ty.code()), a.ty.code());
            if let SwingResult::Contact(b) = &res.swing {
                let label = format!("{:.0} mph {:.0}°", mps_to_mph(b.exit_speed), rad_to_deg(b.launch_angle));
                crate::rr::log_flight(rec, &format!("world/swings/{i:03}/batted"), &b.flight, [255, 255, 255], &label);
            }
        }
    }
    let mean = |v: &[f64]| v.iter().sum::<f64>() / v.len().max(1) as f64;
    let sd = |v: &[f64]| {
        let m = mean(v);
        (v.iter().map(|x| (x - m) * (x - m)).sum::<f64>() / v.len().max(1) as f64).sqrt()
    };
    let c = contact.max(1) as f64;
    println!("{} pitches ({}), perfect perception, noise scale {}", a.n, a.ty.code(), a.k);
    println!("contact {contact}, whiff {miss} ({:.1}% whiff)", 100.0 * miss as f64 / a.n as f64);
    println!("EV mean {:.1} mph (sd {:.1}), LA mean {:.1}° (sd {:.1})", mean(&evs), sd(&evs), mean(&las), sd(&las));
    println!(
        "GB {:.0}%  LD {:.0}%  FB {:.0}%  PU {:.0}%  hard-hit {:.0}%",
        100.0 * buckets[0] as f64 / c,
        100.0 * buckets[1] as f64 / c,
        100.0 * buckets[2] as f64 / c,
        100.0 * buckets[3] as f64 / c,
        100.0 * buckets[4] as f64 / c
    );
}
