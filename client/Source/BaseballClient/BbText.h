// Pictures painted in code: a canvas of pixels, boxes, discs, and block capitals from a
// five-by-seven dot alphabet. The scoreboard and the signs on the fence are painted with it
// (docs/park-visuals.md, step 5); no font or picture is loaded from a file.
#pragma once

#include "CoreMinimal.h"

struct FBbCanvas
{
	int32 W, H;
	/** Rows from the top of the picture down. */
	TArray<FColor> Px;

	FBbCanvas(int32 InW, int32 InH, const FLinearColor& Back)
		: W(InW), H(InH)
	{
		Px.Init(Ink(Back), W * H);
	}

	static FColor Ink(const FLinearColor& C)
	{
		FLinearColor O = C;
		O.A = 1.f;
		return O.ToFColor(true);
	}

	void Box(int32 X0, int32 Y0, int32 X1, int32 Y1, const FLinearColor& C)
	{
		const FColor K = Ink(C);
		for (int32 Y = FMath::Max(Y0, 0); Y < FMath::Min(Y1, H); ++Y)
		{
			for (int32 X = FMath::Max(X0, 0); X < FMath::Min(X1, W); ++X)
			{
				Px[Y * W + X] = K;
			}
		}
	}

	void Disc(double Cx, double Cy, double R, const FLinearColor& C)
	{
		const FColor K = Ink(C);
		for (int32 Y = FMath::Max(FMath::FloorToInt32(Cy - R), 0); Y < FMath::Min(FMath::CeilToInt32(Cy + R) + 1, H); ++Y)
		{
			for (int32 X = FMath::Max(FMath::FloorToInt32(Cx - R), 0); X < FMath::Min(FMath::CeilToInt32(Cx + R) + 1, W); ++X)
			{
				if (FMath::Square(X + 0.5 - Cx) + FMath::Square(Y + 0.5 - Cy) <= R * R)
				{
					Px[Y * W + X] = K;
				}
			}
		}
	}

	/** The seven rows of a character, five dots each (the left dot is bit 4), or nothing for
	 *  a character the alphabet does not have. */
	static const uint8* Glyph(TCHAR Ch)
	{
		struct FGlyph
		{
			TCHAR Ch;
			uint8 Rows[7];
		};
		static const FGlyph Glyphs[] = {
			{ TEXT('A'), { 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 } },
			{ TEXT('B'), { 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E } },
			{ TEXT('C'), { 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E } },
			{ TEXT('D'), { 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E } },
			{ TEXT('E'), { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F } },
			{ TEXT('F'), { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 } },
			{ TEXT('G'), { 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F } },
			{ TEXT('H'), { 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 } },
			{ TEXT('I'), { 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E } },
			{ TEXT('J'), { 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C } },
			{ TEXT('K'), { 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11 } },
			{ TEXT('L'), { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F } },
			{ TEXT('M'), { 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11 } },
			{ TEXT('N'), { 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11 } },
			{ TEXT('O'), { 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E } },
			{ TEXT('P'), { 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10 } },
			{ TEXT('Q'), { 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D } },
			{ TEXT('R'), { 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11 } },
			{ TEXT('S'), { 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E } },
			{ TEXT('T'), { 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 } },
			{ TEXT('U'), { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E } },
			{ TEXT('V'), { 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04 } },
			{ TEXT('W'), { 0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11 } },
			{ TEXT('X'), { 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11 } },
			{ TEXT('Y'), { 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04 } },
			{ TEXT('Z'), { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F } },
			{ TEXT('0'), { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E } },
			{ TEXT('1'), { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E } },
			{ TEXT('2'), { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F } },
			{ TEXT('3'), { 0x1E, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1E } },
			{ TEXT('4'), { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 } },
			{ TEXT('5'), { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E } },
			{ TEXT('6'), { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E } },
			{ TEXT('7'), { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 } },
			{ TEXT('8'), { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E } },
			{ TEXT('9'), { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C } },
			{ TEXT('-'), { 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 } },
			{ TEXT('&'), { 0x0C, 0x12, 0x14, 0x08, 0x15, 0x12, 0x0D } },
			{ TEXT('\''), { 0x04, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00 } },
			{ TEXT('.'), { 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C } },
			{ TEXT('!'), { 0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04 } },
		};
		for (const FGlyph& G : Glyphs)
		{
			if (G.Ch == Ch)
			{
				return G.Rows;
			}
		}
		return nullptr;
	}

	/** How wide a line is with dots Sx pixels apart: five dots a character and one between. */
	static int32 TextW(const FString& S, int32 Sx)
	{
		return S.Len() > 0 ? (S.Len() * 6 - 1) * Sx : 0;
	}

	/** A line of capitals centred on (Cx, Cy), its dots Sx by Sy pixels apart. Gap pixels are
	 *  left dark between dots (0: solid strokes, as paint; 1 or more: lamps, as a board). */
	void Text(const FString& S, int32 Cx, int32 Cy, int32 Sx, int32 Sy, const FLinearColor& C, int32 Gap = 0)
	{
		const int32 X0 = Cx - TextW(S, Sx) / 2, Y0 = Cy - 7 * Sy / 2;
		for (int32 K = 0; K < S.Len(); ++K)
		{
			const uint8* Rows = Glyph(S[K]);
			if (!Rows)
			{
				continue;
			}
			for (int32 R = 0; R < 7; ++R)
			{
				for (int32 D = 0; D < 5; ++D)
				{
					if (Rows[R] & (0x10 >> D))
					{
						const int32 X = X0 + (K * 6 + D) * Sx, Y = Y0 + R * Sy;
						Box(X, Y, X + Sx - Gap, Y + Sy - Gap, C);
					}
				}
			}
		}
	}
};
